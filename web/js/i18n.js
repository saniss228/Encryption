  const AVAILABLE = [
    { code: 'ru', label: 'Русский' },
    { code: 'en', label: 'English' },
    { code: 'es', label: 'Español' },
    { code: 'de', label: 'Deutsch' },
  ];

  let current = 'ru';
  let auto = true;

  function detect() {
    const langs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'ru']);
    for (const l of langs) {
      const code = String(l).slice(0, 2).toLowerCase();
      if (DICT[code]) return code;
    }
    return 'en';
  }

  function t(key, vars) {
    let s = (DICT[current] && DICT[current][key]) || DICT.en[key] || DICT.ru[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(String(vars[k])); });
    }
    return s;
  }

  function setLocale(code, isAuto) {
    if (code && DICT[code]) { current = code; auto = !!isAuto; }
    else if (isAuto !== false) { current = detect(); auto = true; }
    try {
      document.documentElement.setAttribute('lang', current);
      document.documentElement.setAttribute('data-locale', current);
    } catch (e) {}
    return current;
  }

  /** Проставляет переводы элементам с data-i18n / data-i18n-ph / data-i18n-title. */
  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  }

  global.I18N = {
    t, setLocale, apply, available: AVAILABLE,
    detect, get locale() { return current; }, get isAuto() { return auto; },
  };
  global.t = t;
  global.DICT = DICT;
